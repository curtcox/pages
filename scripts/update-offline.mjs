import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../',import.meta.url);
const assets = ['index.html','gallery.html','icon.svg','manifest.webmanifest'];
async function walk(dir) { for (const item of await fs.readdir(new URL(dir+'/',root),{withFileTypes:true})) { const path = dir+'/'+item.name; if (item.isDirectory()) await walk(path); else assets.push(path); } }
for (const dir of ['src','ace','vendor','icons','gallery/previews']) await walk(dir);
assets.sort();
const hashes = {};
for (const path of assets) hashes[path] = createHash('sha256').update(await fs.readFile(new URL(path,root))).digest('hex');
const sw = await fs.readFile(new URL('service-worker.js',root));
const version = 'pagesonline-'+createHash('sha256').update(JSON.stringify(hashes)).update(sw).digest('hex').slice(0,16);
const output = '// GENERATED by scripts/update-offline.mjs.\nconst OfflineAssets = '+JSON.stringify({version,assets,hashes},null,2)+';\nif (typeof module !== "undefined") module.exports = OfflineAssets;\n';
const target = new URL('offline-assets.js',root);
if (process.argv.includes('--check')) { if (await fs.readFile(target,'utf8') !== output) throw Error('Offline assets are stale. Run npm run offline.'); console.log(assets.length+' offline assets verified.'); }
else { await fs.writeFile(target,output); console.log('Offline cache: '+version+' ('+assets.length+' files)'); }
